package pan.dromara.dbtool.core.dialect;

import cn.hutool.core.util.StrUtil;
import org.dromara.common.core.exception.ServiceException;
import pan.dromara.dbtool.domain.vo.DbColumnVo;

import java.util.Locale;

/**
 * PostgreSQL 方言适配器(首个非 MySQL 方言, P0 回归基线)
 * <p>实现差异点:
 * <ul>
 *   <li>元数据: 基于 pg_catalog(pg_database/pg_class/pg_attribute/pg_constraint/pg_index/pg_trigger),
 *       结果集列别名与 MySQL information_schema 对齐, 上层解析逻辑无需改动;</li>
 *   <li>分页: LIMIT size OFFSET offset(MySQL 为 LIMIT offset,size);</li>
 *   <li>标识符: 双引号;</li>
 *   <li>DDL: 无 SHOW CREATE TABLE, 建表由元数据重建; 建库无 IF NOT EXISTS;
 *       改列通过 ALTER COLUMN TYPE / SET / DROP 子句, 不支持改名(返回 null 由上层提示);</li>
 *   <li>列定义: 无 AUTO_INCREMENT/COMMENT 列级语法, 自增用 GENERATED BY DEFAULT AS IDENTITY,
 *       注释需独立 COMMENT ON(列定义 DDL 内不携带)。</li>
 * </ul></p>
 *
 * @author doubao
 */
public class PostgreSqlDialectAdapter implements DbDialectAdapter {

    @Override
    public boolean supports(String dbType) {
        if (dbType == null) {
            return false;
        }
        String t = dbType.trim().toUpperCase(Locale.ROOT);
        // PostgreSQL 协议/方言兼容族(C.3.30): 国产 PG(人大金仓/瀚高/南大通用)、
        // 衍生与云(Greenplum/EDB/CockroachDB/YugabyteDB/TimescaleDB/Redshift)。
        // 均基于 pg_catalog 元数据, 同一适配器适用; 个别差异按"已适配待实测"标注。
        // 注: GBase 8a 为 MySQL 兼容方言(反引号/INFORMATION_SCHEMA/LIMIT 分页),
        // C.3.32 起归入 MySqlDialectAdapter, 不再由 PG 适配器承接
        return "POSTGRESQL".equals(t) || "KINGBASE".equals(t)
            || "HIGHGO".equals(t) || "HIGRES".equals(t)
            || "GREENPLUM".equals(t) || "EDB".equals(t) || "COCKROACHDB".equals(t)
            || "YUGABYTEDB".equals(t) || "TIMESCALEDB".equals(t) || "REDSHIFT".equals(t);
    }

    @Override
    public String quote(String name) {
        return "\"" + (name == null ? "" : name.replace("\"", "\"\"")) + "\"";
    }

    @Override
    public String databasesSql() {
        return "SELECT datname AS SCHEMA_NAME FROM pg_database WHERE NOT datistemplate ORDER BY datname";
    }

    @Override
    public String tablesSql() {
        return "SELECT c.relname AS TABLE_NAME, "
            + "COALESCE(obj_description(c.oid), '') AS TABLE_COMMENT, "
            + "CASE c.relkind WHEN 'r' THEN 'BASE TABLE' WHEN 'p' THEN 'BASE TABLE' "
            + "WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' ELSE 'OTHER' END AS TABLE_TYPE, "
            + "'' AS ENGINE, "
            + "COALESCE(c.reltuples::bigint, 0) AS TABLE_ROWS, "
            + "'' AS CREATE_TIME "
            + "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            + "WHERE n.nspname = ? AND c.relkind IN ('r','p','v','m') AND NOT c.relispartition "
            + "ORDER BY TABLE_TYPE, TABLE_NAME";
    }

    @Override
    public String columnsSql() {
        return "SELECT a.attname AS COLUMN_NAME, "
            + "format_type(a.atttypid, a.atttypmod) AS DATA_TYPE, "
            + "format_type(a.atttypid, a.atttypmod) AS COLUMN_TYPE, "
            + "CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END AS IS_NULLABLE, "
            + "COALESCE(pg_get_expr(ad.adbin, ad.adrelid), '') AS COLUMN_DEFAULT, "
            + "COALESCE(col_description(a.attrelid, a.attnum), '') AS COLUMN_COMMENT, "
            + "CASE WHEN pk.attnum IS NOT NULL THEN 'PRI' ELSE '' END AS COLUMN_KEY, "
            + "CASE WHEN a.attidentity <> '' OR a.attgenerated <> '' THEN 'auto_increment' ELSE '' END AS EXTRA, "
            + "'' AS CHARACTER_SET_NAME, "
            + "'' AS COLLATION_NAME "
            + "FROM pg_attribute a "
            + "JOIN pg_class c ON c.oid = a.attrelid "
            + "JOIN pg_namespace n ON n.oid = c.relnamespace "
            + "LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum "
            + "LEFT JOIN (SELECT conrelid, unnest(conkey) AS attnum FROM pg_constraint WHERE contype = 'p') pk "
            + "ON pk.conrelid = a.attrelid AND pk.attnum = a.attnum "
            + "WHERE n.nspname = ? AND c.relname = ? AND a.attnum > 0 AND NOT a.attisdropped "
            + "ORDER BY a.attnum";
    }

    @Override
    public String indexesSql() {
        return "SELECT i.relname AS INDEX_NAME, "
            + "COALESCE(a.attname, '') AS COLUMN_NAME, "
            + "x.ord AS SEQ_IN_INDEX, "
            + "CASE WHEN ix.indisunique THEN 0 ELSE 1 END AS NON_UNIQUE, "
            + "'' AS INDEX_TYPE, "
            + "'' AS INDEX_COMMENT "
            + "FROM pg_class t "
            + "JOIN pg_index ix ON ix.indrelid = t.oid "
            + "JOIN pg_class i ON i.oid = ix.indexrelid "
            + "JOIN pg_namespace n ON n.oid = t.relnamespace "
            + "JOIN unnest(ix.indkey) WITH ORDINALITY AS x(attnum, ord) ON true "
            + "LEFT JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = x.attnum "
            + "WHERE n.nspname = ? AND t.relname = ? AND t.relkind IN ('r','p','m') "
            + "ORDER BY i.relname, x.ord";
    }

    @Override
    public String constraintsSql() {
        return "SELECT c.conname AS CONSTRAINT_NAME, "
            + "CASE c.contype WHEN 'p' THEN 'PRIMARY KEY' WHEN 'u' THEN 'UNIQUE' "
            + "WHEN 'f' THEN 'FOREIGN KEY' WHEN 'c' THEN 'CHECK' ELSE 'OTHER' END AS CONSTRAINT_TYPE, "
            + "COALESCE(a.attname, '') AS COLUMN_NAME, "
            + "x.ord AS ORDINAL_POSITION "
            + "FROM pg_constraint c "
            + "JOIN pg_class t ON t.oid = c.conrelid "
            + "JOIN pg_namespace n ON n.oid = t.relnamespace "
            + "JOIN unnest(c.conkey) WITH ORDINALITY AS x(attnum, ord) ON true "
            + "LEFT JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = x.attnum "
            + "WHERE n.nspname = ? AND t.relname = ? AND c.contype IN ('p','u','f','c') "
            + "ORDER BY c.conname, x.ord";
    }

    @Override
    public String foreignKeysSql() {
        return "SELECT c.conname AS CONSTRAINT_NAME, "
            + "t.relname AS TABLE_NAME, "
            + "COALESCE(a.attname, '') AS COLUMN_NAME, "
            + "x.ord AS ORDINAL_POSITION, "
            + "rt.relname AS REFERENCED_TABLE_NAME, "
            + "COALESCE(ra.attname, '') AS REFERENCED_COLUMN_NAME, "
            + ruleExpr("confupdtype", "UPDATE_RULE") + ", "
            + ruleExpr("confdeltype", "DELETE_RULE") + " "
            + "FROM pg_constraint c "
            + "JOIN pg_class t ON t.oid = c.conrelid "
            + "JOIN pg_namespace n ON n.oid = t.relnamespace "
            + "JOIN unnest(c.conkey) WITH ORDINALITY AS x(attnum, ord) ON true "
            + "LEFT JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = x.attnum "
            + "JOIN unnest(c.confkey) WITH ORDINALITY AS y(attnum, ord) ON y.ord = x.ord "
            + "LEFT JOIN pg_attribute ra ON ra.attrelid = c.confrelid AND ra.attnum = y.attnum "
            + "JOIN pg_class rt ON rt.oid = c.confrelid "
            + "WHERE n.nspname = ? AND t.relname = ? AND c.contype = 'f' "
            + "ORDER BY c.conname, x.ord";
    }

    @Override
    public String referencesSql() {
        return "SELECT c.conname AS CONSTRAINT_NAME, "
            + "ct.relname AS TABLE_NAME, "
            + "COALESCE(a.attname, '') AS COLUMN_NAME, "
            + "x.ord AS ORDINAL_POSITION, "
            + "t.relname AS REFERENCED_TABLE_NAME, "
            + "COALESCE(ra.attname, '') AS REFERENCED_COLUMN_NAME, "
            + ruleExpr("confupdtype", "UPDATE_RULE") + ", "
            + ruleExpr("confdeltype", "DELETE_RULE") + " "
            + "FROM pg_constraint c "
            + "JOIN pg_class ct ON ct.oid = c.conrelid "
            + "JOIN pg_namespace n ON n.oid = ct.relnamespace "
            + "JOIN pg_class t ON t.oid = c.confrelid "
            + "JOIN unnest(c.conkey) WITH ORDINALITY AS x(attnum, ord) ON true "
            + "LEFT JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = x.attnum "
            + "JOIN unnest(c.confkey) WITH ORDINALITY AS y(attnum, ord) ON y.ord = x.ord "
            + "LEFT JOIN pg_attribute ra ON ra.attrelid = c.confrelid AND ra.attnum = y.attnum "
            + "WHERE n.nspname = ? AND t.relname = ? AND c.contype = 'f' "
            + "ORDER BY ct.relname, c.conname, x.ord";
    }

    private static String ruleExpr(String col, String alias) {
        return "CASE c." + col + " WHEN 'c' THEN 'CASCADE' WHEN 'r' THEN 'RESTRICT' "
            + "WHEN 'n' THEN 'SET NULL' WHEN 'd' THEN 'SET DEFAULT' ELSE 'NO ACTION' END AS " + alias;
    }

    @Override
    public String triggersSql() {
        return "SELECT tg.tgname AS TRIGGER_NAME, "
            + "CASE WHEN tg.tgtype & 2 = 2 THEN 'BEFORE' ELSE 'AFTER' END AS ACTION_TIMING, "
            + "CASE WHEN tg.tgtype & 4 <> 0 THEN 'INSERT' "
            + "WHEN tg.tgtype & 8 <> 0 THEN 'DELETE' "
            + "WHEN tg.tgtype & 16 <> 0 THEN 'UPDATE' ELSE 'OTHER' END AS EVENT_MANIPULATION, "
            + "t.relname AS EVENT_OBJECT_TABLE, "
            + "pg_get_triggerdef(tg.oid) AS ACTION_STATEMENT, "
            + "'' AS CREATED "
            + "FROM pg_trigger tg "
            + "JOIN pg_class t ON t.oid = tg.tgrelid "
            + "JOIN pg_namespace n ON n.oid = t.relnamespace "
            + "WHERE n.nspname = ? AND t.relname = ? AND NOT tg.tgisinternal "
            + "ORDER BY tg.tgname";
    }

    @Override
    public String paginate(String sql, int offset, int size) {
        return sql + " LIMIT " + size + " OFFSET " + offset;
    }

    @Override
    public String showCreateTableSql(String schema, String table) {
        // PostgreSQL 无 SHOW CREATE TABLE, 返回 null 由上层按列元数据重建
        return null;
    }

    @Override
    public String createDatabaseSql(String dbName, String charset) {
        // PG 的 CREATE DATABASE 无 IF NOT EXISTS; 字符集参数(MySQL 风格)不适用, 忽略
        return "CREATE DATABASE " + quote(dbName);
    }

    @Override
    public String dropTableSql(String schema, String table) {
        return "DROP TABLE IF EXISTS " + quote(schema) + "." + quote(table);
    }

    @Override
    public String renameTableSql(String schema, String oldName, String newName) {
        return "ALTER TABLE " + quote(schema) + "." + quote(oldName) + " RENAME TO " + quote(newName);
    }

    @Override
    public String addColumnSql(String schema, String table, String colDdl) {
        return "ALTER TABLE " + quote(schema) + "." + quote(table) + " ADD COLUMN " + colDdl;
    }

    @Override
    public String dropColumnSql(String schema, String table, String column) {
        return "ALTER TABLE " + quote(schema) + "." + quote(table) + " DROP COLUMN " + quote(column);
    }

    @Override
    public String modifyColumnSql(String schema, String table, String oldColumnName, DbColumnVo column) {
        boolean rename = StrUtil.isNotBlank(oldColumnName) && !oldColumnName.equals(column.getColumnName());
        if (rename) {
            // PG 的 RENAME COLUMN 不能与 TYPE/默认值修改合并; 暂不支持一次调用内改名
            return null;
        }
        String type = StrUtil.isNotBlank(column.getColumnType()) ? column.getColumnType() : column.getDataType();
        if (StrUtil.isBlank(type)) {
            throw new ServiceException("列类型不能为空");
        }
        String col = quote(column.getColumnName());
        StringBuilder sb = new StringBuilder("ALTER TABLE ").append(quote(schema)).append('.').append(quote(table));
        sb.append(" ALTER COLUMN ").append(col).append(" TYPE ").append(type);
        boolean notNull = column.getNullable() != null && "NO".equalsIgnoreCase(column.getNullable());
        sb.append(", ALTER COLUMN ").append(col).append(notNull ? " SET NOT NULL" : " DROP NOT NULL");
        String def = column.getDefaultValue();
        if (def != null && !def.isEmpty() && !"NULL".equalsIgnoreCase(def)) {
            sb.append(", ALTER COLUMN ").append(col).append(" SET DEFAULT ").append(defaultLiteral(column.getDataType(), def));
        } else {
            sb.append(", ALTER COLUMN ").append(col).append(" DROP DEFAULT");
        }
        return sb.toString();
    }

    @Override
    public String columnDdl(DbColumnVo c) {
        String type = StrUtil.isNotBlank(c.getColumnType()) ? c.getColumnType() : c.getDataType();
        if (StrUtil.isBlank(type)) {
            throw new ServiceException("列类型不能为空");
        }
        boolean autoInc = c.getExtra() != null && c.getExtra().toLowerCase(Locale.ROOT).contains("auto_increment");
        StringBuilder sb = new StringBuilder(quote(c.getColumnName())).append(' ').append(type);
        if (autoInc) {
            // MySQL 的 AUTO_INCREMENT 在 PG 中对应 identity 列
            sb.append(" GENERATED BY DEFAULT AS IDENTITY");
            return sb.toString();
        }
        boolean notNull = c.getNullable() != null && "NO".equalsIgnoreCase(c.getNullable());
        sb.append(notNull ? " NOT NULL" : " NULL");
        String def = c.getDefaultValue();
        if (def != null && !def.isEmpty() && !"NULL".equalsIgnoreCase(def)) {
            sb.append(" DEFAULT ").append(defaultLiteral(c.getDataType(), def));
        }
        // PG 无列级 COMMENT 语法, 注释需独立 COMMENT ON(由上层决定是否补充)
        return sb.toString();
    }

    private String defaultLiteral(String dataType, String def) {
        if (dataType == null) {
            return "'" + def.replace("'", "''") + "'";
        }
        String dt = dataType.toLowerCase(Locale.ROOT);
        boolean numeric = dt.contains("int") || dt.contains("decimal") || dt.contains("numeric")
            || dt.contains("double") || dt.contains("float") || dt.contains("serial") || dt.contains("bool")
            || dt.contains("real") || dt.contains("bigint") || dt.contains("smallint") || dt.contains("money");
        return numeric ? def : "'" + def.replace("'", "''") + "'";
    }
}
