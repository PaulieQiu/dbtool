package pan.dromara.dbtool.core.dialect;

import cn.hutool.core.util.StrUtil;
import org.dromara.common.core.exception.ServiceException;
import pan.dromara.dbtool.domain.vo.DbColumnVo;

import java.util.Locale;
import java.util.regex.Pattern;

/**
 * Oracle 方言适配器(P0 第二个非 MySQL 方言)
 * <p>实现差异点:
 * <ul>
 *   <li>元数据: 基于 all_* 数据字典视图(all_tables/all_tab_columns/all_constraints/all_indexes/all_triggers),
 *       结果集列别名与 MySQL information_schema 对齐, 上层解析逻辑无需改动;
 *       占位符顺序与 MySQL 一致(owner=?, objectName=?), 首占位符也可指向其他 schema(用户可浏览 all_* 可见对象);</li>
 *   <li>分页: 12c+ 的 OFFSET n ROWS FETCH NEXT m ROWS ONLY(老版本 11g 及以下需 ROWNUM 包装, 前端能力矩阵标注);</li>
 *   <li>标识符: 双引号;</li>
 *   <li>建库: Oracle 无实例级 CREATE DATABASE, createDatabaseSql() 返回 null 由上层提示;</li>
 *   <li>建表 DDL: 无 SHOW CREATE TABLE, 按列元数据重建(mapType 的 oracle 分支: NUMBER/VARCHAR2/CLOB/BLOB/TIMESTAMP);</li>
 *   <li>列定义: 无 AUTO_INCREMENT, 12c+ 自增列用 GENERATED BY DEFAULT AS IDENTITY;
 *       无列级 COMMENT 语法(需独立 COMMENT ON COLUMN);</li>
 *   <li>改列: MODIFY 支持类型/默认值/空值, 不支持改名(返回 null); 触发器正文需 all_source 解析, 元数据列置空。</li>
 * </ul></p>
 *
 * @author doubao
 */
public class OracleDialectAdapter implements DbDialectAdapter {

    private static final Pattern ORACLE_FUNCTION_DEFAULT = Pattern.compile("^[A-Z_]+(\\(.*\\))?$");

    @Override
    public boolean supports(String dbType) {
        return dbType != null && "ORACLE".equalsIgnoreCase(dbType.trim());
    }

    @Override
    public String quote(String name) {
        return "\"" + (name == null ? "" : name.replace("\"", "\"\"")) + "\"";
    }

    @Override
    public String databasesSql() {
        // Oracle 无"数据库列表", 返回当前用户可见的 schema 列表(含系统用户, 前端可按需过滤)
        return "SELECT username AS SCHEMA_NAME FROM all_users ORDER BY username";
    }

    @Override
    public String tablesSql() {
        return "SELECT t.table_name AS TABLE_NAME, "
            + "COALESCE(c.comments, '') AS TABLE_COMMENT, "
            + "'BASE TABLE' AS TABLE_TYPE, '' AS ENGINE, 0 AS TABLE_ROWS, '' AS CREATE_TIME "
            + "FROM all_tables t "
            + "LEFT JOIN all_tab_comments c ON c.owner = t.owner AND c.table_name = t.table_name "
            + "WHERE t.owner = ? AND t.table_name NOT LIKE 'BIN$%' "
            + "UNION ALL "
            + "SELECT v.view_name AS TABLE_NAME, "
            + "COALESCE(c.comments, '') AS TABLE_COMMENT, "
            + "'VIEW' AS TABLE_TYPE, '' AS ENGINE, 0 AS TABLE_ROWS, '' AS CREATE_TIME "
            + "FROM all_views v "
            + "LEFT JOIN all_tab_comments c ON c.owner = v.owner AND c.table_name = v.view_name "
            + "WHERE v.owner = ? AND v.view_name NOT LIKE 'BIN$%' "
            + "ORDER BY TABLE_TYPE, TABLE_NAME";
    }

    @Override
    public String columnsSql() {
        return "SELECT tc.column_name AS COLUMN_NAME, "
            + "tc.data_type AS DATA_TYPE, "
            + "CASE "
            + "WHEN tc.data_type IN ('VARCHAR2','VARCHAR','CHAR','NCHAR','NVARCHAR2','RAW') THEN tc.data_type || '(' || tc.char_length || ')' "
            + "WHEN tc.data_type = 'NUMBER' AND tc.data_precision IS NOT NULL AND tc.data_scale IS NOT NULL THEN tc.data_type || '(' || tc.data_precision || ',' || tc.data_scale || ')' "
            + "WHEN tc.data_type = 'NUMBER' AND tc.data_precision IS NOT NULL THEN tc.data_type || '(' || tc.data_precision || ')' "
            + "ELSE tc.data_type END AS COLUMN_TYPE, "
            + "CASE tc.nullable WHEN 'Y' THEN 'YES' ELSE 'NO' END AS IS_NULLABLE, "
            + "COALESCE(tc.data_default, '') AS COLUMN_DEFAULT, "
            + "COALESCE(cc.comments, '') AS COLUMN_COMMENT, "
            + "CASE WHEN pk.column_name IS NOT NULL THEN 'PRI' ELSE '' END AS COLUMN_KEY, "
            + "'' AS EXTRA, "
            + "'' AS CHARACTER_SET_NAME, "
            + "'' AS COLLATION_NAME "
            + "FROM all_tab_columns tc "
            + "LEFT JOIN all_col_comments cc ON cc.owner = tc.owner AND cc.table_name = tc.table_name AND cc.column_name = tc.column_name "
            + "LEFT JOIN (SELECT cc2.owner, cc2.table_name, cc2.column_name "
            + "FROM all_constraints c JOIN all_cons_columns cc2 "
            + "ON cc2.owner = c.owner AND cc2.constraint_name = c.constraint_name AND cc2.table_name = c.table_name "
            + "WHERE c.constraint_type = 'P') pk "
            + "ON pk.owner = tc.owner AND pk.table_name = tc.table_name AND pk.column_name = tc.column_name "
            + "WHERE tc.owner = ? AND tc.table_name = ? "
            + "ORDER BY tc.column_id";
    }

    @Override
    public String indexesSql() {
        return "SELECT i.index_name AS INDEX_NAME, "
            + "COALESCE(ic.column_name, '') AS COLUMN_NAME, "
            + "ic.column_position AS SEQ_IN_INDEX, "
            + "CASE WHEN i.uniqueness = 'UNIQUE' THEN 0 ELSE 1 END AS NON_UNIQUE, "
            + "i.index_type AS INDEX_TYPE, "
            + "'' AS INDEX_COMMENT "
            + "FROM all_indexes i "
            + "LEFT JOIN all_ind_columns ic ON ic.index_owner = i.owner AND ic.index_name = i.index_name "
            + "AND ic.table_owner = i.table_owner AND ic.table_name = i.table_name "
            + "WHERE i.table_owner = ? AND i.table_name = ? AND i.index_type <> 'LOB' "
            + "ORDER BY i.index_name, ic.column_position";
    }

    @Override
    public String constraintsSql() {
        return "SELECT c.constraint_name AS CONSTRAINT_NAME, "
            + "CASE c.constraint_type WHEN 'P' THEN 'PRIMARY KEY' WHEN 'U' THEN 'UNIQUE' "
            + "WHEN 'R' THEN 'FOREIGN KEY' WHEN 'C' THEN 'CHECK' ELSE 'OTHER' END AS CONSTRAINT_TYPE, "
            + "COALESCE(cc.column_name, '') AS COLUMN_NAME, "
            + "cc.position AS ORDINAL_POSITION "
            + "FROM all_constraints c "
            + "LEFT JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name AND cc.table_name = c.table_name "
            + "WHERE c.owner = ? AND c.table_name = ? AND c.constraint_type IN ('P','U','R','C') "
            + "ORDER BY c.constraint_name, cc.position";
    }

    @Override
    public String foreignKeysSql() {
        return "SELECT c.constraint_name AS CONSTRAINT_NAME, "
            + "c.table_name AS TABLE_NAME, "
            + "COALESCE(cc.column_name, '') AS COLUMN_NAME, "
            + "cc.position AS ORDINAL_POSITION, "
            + "pc.table_name AS REFERENCED_TABLE_NAME, "
            + "pcc.column_name AS REFERENCED_COLUMN_NAME, "
            + "'NO ACTION' AS UPDATE_RULE, "
            + "CASE c.delete_rule WHEN 'CASCADE' THEN 'CASCADE' WHEN 'SET NULL' THEN 'SET NULL' "
            + "WHEN 'SET DEFAULT' THEN 'SET DEFAULT' ELSE 'NO ACTION' END AS DELETE_RULE "
            + "FROM all_constraints c "
            + "JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name AND cc.table_name = c.table_name "
            + "JOIN all_constraints pc ON pc.owner = c.r_owner AND pc.constraint_name = c.r_constraint_name "
            + "JOIN all_cons_columns pcc ON pcc.owner = pc.owner AND pcc.constraint_name = pc.constraint_name AND pcc.position = cc.position "
            + "WHERE c.owner = ? AND c.table_name = ? AND c.constraint_type = 'R' "
            + "ORDER BY c.constraint_name, cc.position";
    }

    @Override
    public String referencesSql() {
        // 占位符: 1=被引用表 owner, 2=被引用表名(与 MySQL 的 TABLE_SCHEMA/REFERENCED_TABLE_NAME 顺序一致)
        return "SELECT c.constraint_name AS CONSTRAINT_NAME, "
            + "c.table_name AS TABLE_NAME, "
            + "COALESCE(cc.column_name, '') AS COLUMN_NAME, "
            + "cc.position AS ORDINAL_POSITION, "
            + "pc.table_name AS REFERENCED_TABLE_NAME, "
            + "pcc.column_name AS REFERENCED_COLUMN_NAME, "
            + "'NO ACTION' AS UPDATE_RULE, "
            + "CASE c.delete_rule WHEN 'CASCADE' THEN 'CASCADE' WHEN 'SET NULL' THEN 'SET NULL' "
            + "WHEN 'SET DEFAULT' THEN 'SET DEFAULT' ELSE 'NO ACTION' END AS DELETE_RULE "
            + "FROM all_constraints c "
            + "JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name AND cc.table_name = c.table_name "
            + "JOIN all_constraints pc ON pc.owner = c.r_owner AND pc.constraint_name = c.r_constraint_name "
            + "JOIN all_cons_columns pcc ON pcc.owner = pc.owner AND pcc.constraint_name = pc.constraint_name AND pcc.position = cc.position "
            + "WHERE c.constraint_type = 'R' AND c.r_owner = ? AND pc.table_name = ? "
            + "ORDER BY c.table_name, c.constraint_name, cc.position";
    }

    @Override
    public String triggersSql() {
        // all_triggers 不含触发器正文(body 在 all_source 中), ACTION_STATEMENT 置空, 前端展示 trigger_type/status
        return "SELECT t.trigger_name AS TRIGGER_NAME, "
            + "t.action_timing AS ACTION_TIMING, "
            + "t.trigger_type AS EVENT_MANIPULATION, "
            + "t.table_name AS EVENT_OBJECT_TABLE, "
            + "'' AS ACTION_STATEMENT, "
            + "'' AS CREATED "
            + "FROM all_triggers t "
            + "WHERE t.owner = ? AND t.table_name = ? "
            + "ORDER BY t.trigger_name";
    }

    @Override
    public String paginate(String sql, int offset, int size) {
        // Oracle 12c+ 分页; 11g 及以下需 ROWNUM 包装(能力矩阵标注)
        return sql + " OFFSET " + offset + " ROWS FETCH NEXT " + size + " ROWS ONLY";
    }

    @Override
    public String showCreateTableSql(String schema, String table) {
        // Oracle 无 SHOW CREATE TABLE, 由上层按列元数据重建
        return null;
    }

    @Override
    public String createDatabaseSql(String dbName, String charset) {
        // Oracle 无实例级 CREATE DATABASE(SYSDBA 特权操作), 由上层提示不支持
        return null;
    }

    @Override
    public String dropTableSql(String schema, String table) {
        // Oracle 23c 前无 DROP TABLE IF EXISTS
        return "DROP TABLE " + quote(schema) + "." + quote(table);
    }

    @Override
    public String renameTableSql(String schema, String oldName, String newName) {
        return "ALTER TABLE " + quote(schema) + "." + quote(oldName) + " RENAME TO " + quote(newName);
    }

    @Override
    public String addColumnSql(String schema, String table, String colDdl) {
        return "ALTER TABLE " + quote(schema) + "." + quote(table) + " ADD (" + colDdl + ")";
    }

    @Override
    public String dropColumnSql(String schema, String table, String column) {
        return "ALTER TABLE " + quote(schema) + "." + quote(table) + " DROP COLUMN " + quote(column);
    }

    @Override
    public String modifyColumnSql(String schema, String table, String oldColumnName, DbColumnVo column) {
        boolean rename = StrUtil.isNotBlank(oldColumnName) && !oldColumnName.equals(column.getColumnName());
        if (rename) {
            // Oracle MODIFY 不支持列改名, 需 RENAME COLUMN(11g+ 支持)单独执行, 一次调用内不合并
            return null;
        }
        String type = StrUtil.isNotBlank(column.getColumnType()) ? column.getColumnType() : column.getDataType();
        if (StrUtil.isBlank(type)) {
            throw new ServiceException("列类型不能为空");
        }
        String col = quote(column.getColumnName());
        StringBuilder sb = new StringBuilder("ALTER TABLE ").append(quote(schema)).append('.').append(quote(table));
        sb.append(" MODIFY (").append(col).append(' ').append(type);
        String def = column.getDefaultValue();
        if (def != null && !def.isEmpty() && !"NULL".equalsIgnoreCase(def)) {
            sb.append(" DEFAULT ").append(defaultLiteral(column.getDataType(), def));
        }
        boolean notNull = column.getNullable() != null && "NO".equalsIgnoreCase(column.getNullable());
        sb.append(notNull ? " NOT NULL" : " NULL");
        return sb.append(')').toString();
    }

    @Override
    public String columnDdl(DbColumnVo c) {
        String type = StrUtil.isNotBlank(c.getColumnType()) ? c.getColumnType() : c.getDataType();
        if (StrUtil.isBlank(type)) {
            throw new ServiceException("列类型不能为空");
        }
        boolean autoInc = c.getExtra() != null && c.getExtra().toLowerCase(Locale.ROOT).contains("auto_increment");
        StringBuilder sb = new StringBuilder(quote(c.getColumnName())).append(' ').append(type);
        if (autoInc) {
            // Oracle 12c+ identity 列
            return sb.append(" GENERATED BY DEFAULT AS IDENTITY").toString();
        }
        boolean notNull = c.getNullable() != null && "NO".equalsIgnoreCase(c.getNullable());
        sb.append(notNull ? " NOT NULL" : " NULL");
        String def = c.getDefaultValue();
        if (def != null && !def.isEmpty() && !"NULL".equalsIgnoreCase(def)) {
            sb.append(" DEFAULT ").append(defaultLiteral(c.getDataType(), def));
        }
        // Oracle 无列级 COMMENT 语法, 注释需独立 COMMENT ON COLUMN(由上层决定是否补充)
        return sb.toString();
    }

    private String defaultLiteral(String dataType, String def) {
        if (ORACLE_FUNCTION_DEFAULT.matcher(def.trim()).matches()) {
            // SYSDATE / CURRENT_TIMESTAMP 等函数或伪列不加引号
            return def;
        }
        if (dataType == null) {
            return "'" + def.replace("'", "''") + "'";
        }
        String dt = dataType.toLowerCase(Locale.ROOT);
        boolean numeric = dt.contains("number") || dt.contains("int") || dt.contains("float")
            || dt.contains("decimal") || dt.contains("numeric") || dt.contains("binary_")
            || dt.contains("real") || dt.contains("double");
        return numeric ? def : "'" + def.replace("'", "''") + "'";
    }
}
